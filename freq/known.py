def deumlaut(s):
    return s.replace("ä", "a").replace("ö", "o").replace("ü", "u")


def place_base(w, names):
    for suf in E_SUFFIXES:
        if not w.lower().endswith(suf) or len(w) - len(suf) < 4:
            continue
        s = w.lower()[:-len(suf)]
        for stem in {s, s[:-1], s[:-2], deumlaut(s), deumlaut(s)[:-1]}:
            for tail in E_TAILS:
                # a bare stem must be a plausible name on its own; with a tail three
                # letters suffice — polnisch reaches Polen as pol+en
                if len(stem) < (4 if tail == "" else 3):
                    continue
                if stem + tail in names:
                    return stem + tail
    return None


