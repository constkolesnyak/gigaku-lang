    if w in HAND_OBVIOUS:
        cut[w] = "transparent internationalism (reviewed by hand)"
        continue
    if w not in KEEP_E:
        b = place_base(w, GEO)
        if b:
            cut[w] = f"derived from the place name {b.capitalize()}"
