def base_adj(stem):
    """stem → the base adjective it declines (fremd→fremd, Best→gut via beste)."""
    for s in (stem, dic.spell.get(stem, stem).lower(), deumlaut(stem)):
        if "adj" in dic.head.get(s, ()):
            return s
        for key in (s, s + "e"):
            for t in dic.fof[key].get("adj", ()):
                return t.lower()
            for t in dic.both[key].get("adj", ()):
                return t.lower()
            if key in dic.degree:
                return sorted(dic.degree[key])[0].lower()
    return None


def d_variants(w):
    l = w.lower()
    vs = {l, l.replace("k", "c"), l.replace("z", "c"),
          l.replace("k", "c").replace("z", "c"), l.replace("sch", "sh"),
          l.replace("ß", "ss")}
    more = set()
    for v in vs:
        for a, b in (("ie", "y"), ("ik", "ic"), ("ik", "ics"), ("ismus", "ism"),
                     ("ität", "ity"), ("in", "ine"), ("ur", "ure"), ("ös", "ous"),
                     ("anz", "ance"), ("enz", "ence"), ("ieren", "ate"),
                     ("ieren", ""), ("iv", "ive"), ("um", ""),
                     # -isch is Greco-Latin -ic: allergisch, chronisch, zynisch —
                     # the 2026-08-25 review found ~100 of these sitting past the
                     # first pass because the transform was missing
                     ("istisch", "istic"), ("isch", "ic"), ("isch", "ical")):
            if v.endswith(a):
                more.add(v[:-len(a)] + b)
    return vs | more


