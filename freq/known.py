    if w[:1].isupper() and pos in ("NOUN", "PROPN", "ADJ") and w not in KEEP_A:
        m = re.match(r"^(.*?)(e|er|es|en)$", w)
        if m and len(m.group(1)) >= 3:
            b = base_adj(m.group(1).lower())
            if b and b in MIG:
                cut[w] = f"nominalisation of {b}, in Migaku"
                continue
    if pos in ("ADJ", "ADV") and w[:1].islower():
        ts = {t.lower() for t in
              dic.fof[lo].get("adj", set()) | dic.both[lo].get("adj", set())
              | dic.fof[lo].get("adv", set()) | dic.both[lo].get("adv", set())
              | dic.degree.get(lo, set())}
        hit = sorted(ts & MIG)
        if hit:
            cut[w] = f"declension/degree of {hit[0]}, in Migaku"
            continue
    if pos == "VERB" and w not in KEEP_C:
        ts = {t.lower() for t in
              dic.fof[lo].get("verb", set()) | dic.both[lo].get("verb", set())}
        hit = sorted(ts & MIG)
